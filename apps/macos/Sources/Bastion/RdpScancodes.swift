import AppKit

/// macOS virtual key codes → PC/AT set-1 scancodes (what RDP sends). Position-based, so the
/// remote keyboard layout decides which character a key produces.
enum RdpScancodes {
    struct Code { let scancode: UInt8; let extended: Bool }

    private static func k(_ s: UInt8, _ e: Bool = false) -> Code { Code(scancode: s, extended: e) }

    static let map: [UInt16: Code] = [
        // Letters
        0x00: k(0x1E), 0x0B: k(0x30), 0x08: k(0x2E), 0x02: k(0x20), 0x0E: k(0x12), 0x03: k(0x21),
        0x05: k(0x22), 0x04: k(0x23), 0x22: k(0x17), 0x26: k(0x24), 0x28: k(0x25), 0x25: k(0x26),
        0x2E: k(0x32), 0x2D: k(0x31), 0x1F: k(0x18), 0x23: k(0x19), 0x0C: k(0x10), 0x0F: k(0x13),
        0x01: k(0x1F), 0x11: k(0x14), 0x20: k(0x16), 0x09: k(0x2F), 0x0D: k(0x11), 0x07: k(0x2D),
        0x10: k(0x15), 0x06: k(0x2C),
        // Digits row
        0x12: k(0x02), 0x13: k(0x03), 0x14: k(0x04), 0x15: k(0x05), 0x17: k(0x06), 0x16: k(0x07),
        0x1A: k(0x08), 0x1C: k(0x09), 0x19: k(0x0A), 0x1D: k(0x0B), 0x1B: k(0x0C), 0x18: k(0x0D),
        // Punctuation
        0x21: k(0x1A), 0x1E: k(0x1B), 0x2A: k(0x2B), 0x29: k(0x27), 0x27: k(0x28), 0x32: k(0x29),
        0x2B: k(0x33), 0x2F: k(0x34), 0x2C: k(0x35), 0x0A: k(0x56),
        // Editing and whitespace
        0x24: k(0x1C), 0x30: k(0x0F), 0x31: k(0x39), 0x33: k(0x0E), 0x35: k(0x01), 0x75: k(0x53, true),
        // Modifiers (⌘ maps to the Windows key)
        0x38: k(0x2A), 0x3C: k(0x36), 0x3B: k(0x1D), 0x3E: k(0x1D, true), 0x3A: k(0x38), 0x3D: k(0x38, true),
        0x37: k(0x5B, true), 0x36: k(0x5C, true), 0x39: k(0x3A),
        // Function keys
        0x7A: k(0x3B), 0x78: k(0x3C), 0x63: k(0x3D), 0x76: k(0x3E), 0x60: k(0x3F), 0x61: k(0x40),
        0x62: k(0x41), 0x64: k(0x42), 0x65: k(0x43), 0x6D: k(0x44), 0x67: k(0x57), 0x6F: k(0x58),
        // Navigation
        0x73: k(0x47, true), 0x77: k(0x4F, true), 0x74: k(0x49, true), 0x79: k(0x51, true),
        0x7B: k(0x4B, true), 0x7C: k(0x4D, true), 0x7D: k(0x50, true), 0x7E: k(0x48, true),
        // Keypad
        0x52: k(0x52), 0x53: k(0x4F), 0x54: k(0x50), 0x55: k(0x51), 0x56: k(0x4B), 0x57: k(0x4C),
        0x58: k(0x4D), 0x59: k(0x47), 0x5B: k(0x48), 0x5C: k(0x49), 0x41: k(0x53), 0x43: k(0x37),
        0x45: k(0x4E), 0x4E: k(0x4A), 0x4B: k(0x35, true), 0x4C: k(0x1C, true),
    ]

    static let modifierFlag: [UInt16: NSEvent.ModifierFlags] = [
        0x38: .shift, 0x3C: .shift, 0x3B: .control, 0x3E: .control, 0x3A: .option, 0x3D: .option,
        0x37: .command, 0x36: .command, 0x39: .capsLock,
    ]
}
