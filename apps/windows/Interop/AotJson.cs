internal sealed partial class AotJsonContext : JsonSerializerContext;

internal static class AotJson
{
    /// <summary>Generated metadata only: no reflection fallback, so a type missing above fails the same way on every
    /// build (ReadyToRun or AOT) instead of only under Native AOT. tests/aot-json-check.py checks the list.</summary>
    internal static readonly IJsonTypeInfoResolver Resolver = AotJsonContext.Default;

    /// <summary>For calls that used the default options.</summary>
    internal static readonly JsonSerializerOptions Options = new() { TypeInfoResolver = Resolver };

    /// <summary>The generated metadata for <typeparamref name="T"/> under these options (their naming and case rules).</summary>
    internal static JsonTypeInfo<T> Info<T>(this JsonSerializerOptions options) => (JsonTypeInfo<T>)options.GetTypeInfo(typeof(T));

    internal static string Write<T>(T value, JsonSerializerOptions options) => JsonSerializer.Serialize(value, options.Info<T>());
    internal static System.Text.Json.Nodes.JsonNode? WriteToNode<T>(T value, JsonSerializerOptions options) => JsonSerializer.SerializeToNode(value, options.Info<T>());
    internal static byte[] WriteToUtf8Bytes<T>(T value, JsonSerializerOptions options) => JsonSerializer.SerializeToUtf8Bytes(value, options.Info<T>());
}
