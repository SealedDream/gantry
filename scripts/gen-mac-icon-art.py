#!/usr/bin/env python3
"""Embed docs/design/icons/*.svg in the Native Mac app as Swift string constants.

The SVGs stay the one source for all four apps (docs/design/ICON-SET.md). Run after
changing any of them; `--check` exits 1 when the Swift file is out of date.
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/design/icons"
OUT = ROOT / "apps/macos/Sources/Bastion/ConnectionIconArt.swift"

def render() -> str:
    lines = ["// Generated by scripts/gen-mac-icon-art.py from docs/design/icons. Do not edit.",
             "", "enum ConnectionIconArt {", "    static let svg: [String: String] = ["]
    for f in sorted(SRC.glob("*.svg")):
        body = f.read_text().strip()
        if '"##' in body:
            sys.exit(f"{f.name}: contains triple quotes")
        lines.append(f'        "{f.stem}": ##"{body}"##,')
    lines += ["    ]", "}", ""]
    return "\n".join(lines)

text = render()
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
OUT.write_text(text)
print(f"wrote {OUT.relative_to(ROOT)}")
