#!/usr/bin/env python3
"""Third-party licence/notice inventory per shipped artifact (Codex L04).

    python3 scripts/notices.py           # regenerate licenses/<artifact>/THIRD_PARTY_NOTICES.txt
    python3 scripts/notices.py --check   # exit 1 when a committed file is stale or a crate has no licence

The files are committed because the Windows build host has no Python; each bundle copies its own
file (apps/macos/bundle.sh, apps/windows/BastionShell.csproj, ui-tauri/src-tauri/tauri.bundle.json).
Only crates linked into the artifact count: normal dependencies, resolved for the artifact's target,
without proc-macros or build-only crates. Identical licence files (ignoring whitespace) are printed once, with every crate
that uses them listed above. Where a crate offers `... OR MIT`, Bastion elects MIT. Run after any Cargo.lock or package-lock.json change.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LICENCE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "unlicense")


@dataclass(frozen=True)
class Artifact:
    name: str
    crates: tuple[str, ...]
    targets: tuple[str, ...]
    npm: str | None = None
    extra: tuple[str, ...] = ()


ARTIFACTS = (
    Artifact("native-mac", ("core-ffi", "rdp-ffi"), ("aarch64-apple-darwin", "x86_64-apple-darwin"), extra=("assets/fonts/OFL.txt",)),
    Artifact("native-win", ("core-cabi", "rdp-ffi"), ("x86_64-pc-windows-msvc",), extra=("assets/fonts/OFL.txt",)),
    # One Tauri bundle config serves both OSes, so its file covers both targets.
    Artifact("tauri", ("ui-tauri/src-tauri", "ui-tauri/rdp-helper"), ("aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc"), npm="ui-tauri"),
)

HEADER = """Third-party software notices for Gantry ({name}).
Generated by scripts/notices.py from the committed lockfiles; do not edit by hand.
OpenH264 is not included: when RDP needs it, Gantry downloads Cisco's binary, which Cisco
licenses under its own terms (https://www.openh264.org/BINARY_LICENSE.txt).
"""


def linked_packages(crate_dir: str, target: str) -> list[dict]:
    """Registry/git packages linked into `crate_dir` for `target` (normal deps, no proc-macros)."""
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT / crate_dir, check=True, capture_output=True, text=True,
    ).stdout
    meta = json.loads(out)
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen: set[str] = set()
    stack = [meta["resolve"]["root"]]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            normal = any(k["kind"] is None for k in dep["dep_kinds"])
            is_macro = any("proc-macro" in t["kind"] for t in by_id[dep["pkg"]]["targets"])
            if normal and not is_macro:
                stack.append(dep["pkg"])
    return [by_id[p] for p in seen if by_id[p]["source"]]  # path crates are Bastion's own


def licence_files(directory: Path) -> list[Path]:
    if not directory.is_dir():
        return []
    return sorted(p for p in directory.iterdir() if p.is_file() and p.name.lower().startswith(LICENCE_PREFIXES))


def elected(licence: str, files: list[Path]) -> list[Path]:
    """For a disjunctive licence that offers MIT, Bastion elects MIT: ship that text and any
    NOTICE/COPYRIGHT files, not the alternatives. Otherwise every licence file ships."""
    if " OR " not in licence or "MIT" not in licence.replace("MIT-0", ""):
        return files
    kept = [f for f in files if "mit" in f.name.lower() or f.name.lower().startswith(("notice", "copyright"))]
    return kept or files


def npm_packages(npm_dir: str) -> list[tuple[str, str, Path]]:
    """Production npm packages (bundled into the web UI), from package-lock.json."""
    lock = json.loads((ROOT / npm_dir / "package-lock.json").read_text())
    result = []
    for path, info in lock.get("packages", {}).items():
        if not path or info.get("dev") or info.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        result.append((f"{name} {info.get('version', '')} (npm)", info.get("license", "UNKNOWN"), ROOT / npm_dir / path))
    return result


def render(artifact: Artifact) -> tuple[str, list[str]]:
    texts: dict[str, tuple[str, list[str]]] = {}
    missing: list[str] = []

    def add(label: str, licence: str, files: list[Path]) -> None:
        if not files:
            missing.append(f"{label}: {licence}")
            return
        for f in elected(licence, files):
            body = f.read_text(errors="replace").strip()
            key = hashlib.sha256(" ".join(body.split()).encode()).hexdigest()
            texts.setdefault(key, (body, []))[1].append(f"{label}: {licence} ({f.name})")

    packages = {}
    for crate in artifact.crates:
        for p in (q for t in artifact.targets for q in linked_packages(crate, t)):
            packages[(p["name"], p["version"])] = p
    for (name, version), p in sorted(packages.items()):
        add(f"{name} {version}", p.get("license") or "UNKNOWN", licence_files(Path(p["manifest_path"]).parent))
    if artifact.npm:
        for label, licence, directory in sorted(npm_packages(artifact.npm)):
            add(label, licence, licence_files(directory))
    for extra in artifact.extra:
        add(extra, "bundled file", [ROOT / extra])

    parts = [HEADER.format(name=artifact.name)]
    for body, users in sorted(texts.values(), key=lambda t: sorted(t[1])[0]):
        parts.append("=" * 78 + "\n" + "\n".join(sorted(users)) + "\n" + "-" * 78 + "\n" + body + "\n")
    if missing:
        parts.append("=" * 78 + "\nPackages that ship no licence file (licence by SPDX id; standard text applies):\n" + "\n".join(sorted(missing)) + "\n")
    return "\n".join(parts), missing


def main(argv: list[str]) -> int:
    check = "--check" in argv
    failed = False
    for artifact in ARTIFACTS:
        if not all((ROOT / c).is_dir() for c in artifact.crates):
            continue  # the public tree has no ui-tauri
        text, missing = render(artifact)
        path = ROOT / "licenses" / artifact.name / "THIRD_PARTY_NOTICES.txt"
        unknown = [m for m in missing if m.endswith("UNKNOWN")]
        if unknown:
            print(f"{artifact.name}: no licence at all for:\n  " + "\n  ".join(unknown))
            failed = True
        if check:
            if not path.exists() or path.read_text() != text:
                print(f"{path.relative_to(ROOT)} is stale: run python3 scripts/notices.py")
                failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"{path.relative_to(ROOT)}: {len(text) // 1024} KiB, {len(missing)} without a licence file")
    if check and not failed:
        print("notices OK")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
