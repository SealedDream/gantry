#!/usr/bin/env python3
"""Write apps/windows/ConnectionIconArt.cs from docs/design/icons (UI-05, D12).

Each SVG is embedded as a string, rendered at run time by WinUI's SvgImageSource (Direct2D SVG). Direct2D does not
draw <mask>, so a monochrome glyph with cut-outs (files-mono, web-mono) is rewritten here: the mask goes, and the
mask's black shapes are drawn on top in the placeholder colour BACKGROUND, which ConnectionIcon replaces with the
surface colour behind the icon (the High Contrast window colour). `--check` exits 1 when the file is out of date.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "docs" / "design" / "icons"
OUT = ROOT / "apps" / "windows" / "ConnectionIconArt.cs"

MASK = re.compile(r'<mask id="([^"]+)">(.*?)</mask>', re.S)


def unmask(svg: str) -> str:
    m = MASK.search(svg)
    if not m:
        return svg
    body = m.group(2)
    # Drop the mask's white backdrop; keep its black shapes (with their transform group) as cut-out shapes.
    body = re.sub(r'<rect width="24" height="24" fill="#fff"/>', "", body)
    cut = body.replace('"#000"', '"BACKGROUND"')
    svg = svg[: m.start()] + svg[m.end():]
    svg = svg.replace(f' mask="url(#{m.group(1)})"', "")
    return svg.replace("</svg>", cut + "</svg>")


def render() -> str:
    lines = [
        "// <auto-generated> by scripts/gen-win-icon-art.py from docs/design/icons. Do not edit; run the script. </auto-generated>",
        "namespace Bastion.Shell;",
        "",
        "internal static class ConnectionIconArt",
        "{",
        "    public static readonly IReadOnlyDictionary<string, string> Svg = new Dictionary<string, string>",
        "    {",
    ]
    for path in sorted(ICONS.glob("*.svg")):
        svg = unmask(path.read_text().strip())
        lines.append(f'        ["{path.stem}"] = "{svg.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}",')
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/gen-win-icon-art.py")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
